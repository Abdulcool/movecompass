import { mkdir,copyFile,readFile,writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { resolve,join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const source=fileURLToPath(new URL('./',import.meta.url));
const root=resolve(source,'../..');
const stage=join(homedir(),'.movecompass-build','esp8266'),output=join(homedir(),'.movecompass-build','bin');
await mkdir(stage,{recursive:true});await mkdir(output,{recursive:true});
await copyFile(join(source,'esp8266.ino'),join(stage,'esp8266.ino'));
await copyFile(join(source,'config.h.example'),join(stage,'config.h'));
const result=spawnSync(process.env.ARDUINO_CLI||'arduino-cli',['compile','--fqbn','esp8266:esp8266:nodemcuv2','--output-dir',output,stage],{stdio:'inherit'});
if(result.error)throw result.error;if(result.status!==0)process.exit(result.status||1);
const binary=await readFile(join(output,'esp8266.ino.bin'));
if(binary[0]!==0xe9 || binary[4096]!==0xe9)throw new Error('Expected merged ESP8266 eboot + application image at offsets 0 and 4096');
const target=join(root,'app','public','firmware');await mkdir(target,{recursive:true});
await writeFile(join(target,'movecompass-esp8266.bin'),binary);
await writeFile(join(target,'manifest.json'),JSON.stringify({name:'MoveCompass patient notifier',version:'0.2.0',new_install_prompt_erase:true,builds:[{chipFamily:'ESP8266',parts:[{path:'movecompass-esp8266.bin',offset:0}]}]},null,2)+'\n');
console.log(`ESP8266 merged eboot + application image: ${binary.length} bytes; flash offset 0`);
